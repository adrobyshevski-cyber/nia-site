#!/usr/bin/env python3
"""Сборка раздела insights из Markdown.

Источник правды — content/articles/*.md. Скрипт пересобирает:
  public/insights/<slug>/index.html   страницы статей
  public/insights/index.html          каталог (рекомендации, карточки, фильтры)
  public/insights/articles.json       метаданные для интерфейса
  public/index.html                   блок «NIA / INSIGHTS» на главной
  public/sitemap.xml                  карта сайта

Запуск: python scripts/build-insights.py
"""

import html
import json
import math
import re
import shutil
import sys
from datetime import date
from pathlib import Path

import mistune
import yaml
from bs4 import BeautifulSoup

REPO = Path(__file__).resolve().parents[1]
PUBLIC = REPO / "public"
CONTENT = REPO / "content" / "articles"
TEMPLATE = REPO / "templates" / "insights-article.html"

SITE = "https://narrativeintelligence.ru"
MARKER = "<!-- generated by scripts/build-insights.py -->"
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
ALLOWED_PRACTICES = {
    "/audit/",
    "/brand/",
    "/practices/culture.html",
    "/practices/economics.html",
    "/practices/strategy.html",
    "/practices/lab.html",
}
REQUIRED_FIELDS = ("title", "slug", "description", "category", "date", "author", "lead", "practice", "practice_label")
MIN_BODY_CHARS = 150
WORDS_PER_MINUTE = 190

# lastmod для статических страниц: обновляйте вручную, когда правите их содержимое
STATIC_LAST_MOD = "2026-11-26"

MD = mistune.create_markdown(escape=True, plugins=["table", "strikethrough", "url"])


def fail(message):
    raise ValueError(message)


def write(path, text):
    """Запись в UTF-8 с LF: на Windows write_text по умолчанию ставит CRLF."""
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def esc(value):
    return html.escape(str(value), quote=True)


def load_articles():
    if not CONTENT.is_dir():
        fail(f"нет папки {CONTENT.relative_to(REPO)}")

    articles = []
    for path in sorted(CONTENT.glob("*.md")):
        raw = path.read_text(encoding="utf-8")
        match = re.match(r"^---\s*\n(.*?)\n---\s*\n(.*)$", raw, re.S)
        if not match:
            fail(f"{path.name}: ожидается YAML front matter между --- и ---")
        meta = yaml.safe_load(match.group(1))
        if not isinstance(meta, dict):
            fail(f"{path.name}: front matter должен быть объектом")
        body = match.group(2).strip()

        for key in REQUIRED_FIELDS:
            if not meta.get(key):
                fail(f"{path.name}: заполните поле {key}")

        slug = str(meta["slug"])
        if not SLUG_RE.fullmatch(slug):
            fail(f"{path.name}: slug должен состоять из латинских букв, цифр и дефисов")
        if any(a["slug"] == slug for a in articles):
            fail(f"{path.name}: slug «{slug}» уже используется")
        if str(meta["practice"]) not in ALLOWED_PRACTICES:
            fail(f"{path.name}: practice должна быть одной из {sorted(ALLOWED_PRACTICES)}")

        day = meta["date"]
        day = day.isoformat() if isinstance(day, date) else str(day)
        try:
            date.fromisoformat(day)
        except ValueError:
            fail(f"{path.name}: дата должна быть в формате YYYY-MM-DD")

        draft = bool(meta.get("draft", False))
        if not draft and len(body) < MIN_BODY_CHARS:
            fail(f"{path.name}: текст короче {MIN_BODY_CHARS} символов — либо допишите, либо draft: true")

        words = len(re.findall(r"\w+", body, flags=re.UNICODE))
        articles.append(
            {
                **meta,
                "slug": slug,
                "date": day,
                "body_html": MD(body),
                "minutes": max(1, math.ceil(words / WORDS_PER_MINUTE)),
                "url": f"/insights/{slug}/",
                "featured": bool(meta.get("featured", False)),
                "draft": draft,
                "source": path.name,
            }
        )

    published = [a for a in articles if not a["draft"]]
    if not published:
        fail("нет опубликованных статей: у всех draft: true")
    return sorted(published, key=lambda a: (a["date"], a["slug"]), reverse=True)


def render_article(article, related):
    template = TEMPLATE.read_text(encoding="utf-8")
    breadcrumb = '<a href="/">NIA</a> / <a href="/insights/">Insights</a> / ' + esc(article["category"])
    eyebrow = esc(f"{article['category'].upper()} / NIA INSIGHTS")
    meta_line = esc(f"{article['author']} · {article['date']} · {article['minutes']} мин чтения")

    also = ""
    if related:
        items = "".join(f'<li><a href="{esc(a["url"])}">{esc(a["title"])}</a></li>' for a in related[:2])
        also = f"<h2>Читайте также</h2><ul>{items}</ul>"

    replacements = {
        "{{TITLE}}": esc(f"{article['title']} | NIA Insights"),
        "{{DESCRIPTION}}": esc(article["description"]),
        "{{URL}}": SITE + article["url"],
        "{{BREADCRUMB}}": breadcrumb,
        "{{EYEBROW}}": eyebrow,
        "{{H1}}": esc(article["title"]),
        "{{LEAD}}": esc(article["lead"]),
        "{{META_LINE}}": meta_line,
        "{{BODY}}": article["body_html"],
        "{{PRACTICE_HREF}}": esc(article["practice"]),
        "{{PRACTICE_LABEL}}": esc(article["practice_label"]),
        "{{ALSO_BLOCK}}": also,
        "{{UID}}": f"insights-{article['slug']}",
        "{{DATE}}": article["date"],
    }
    page = template
    for token, value in replacements.items():
        page = page.replace(token, value)

    leftover = re.findall(r"\{\{[A-Z_]+\}\}", page)
    if leftover:
        fail(f"{article['source']}: не подставлены {leftover}")

    out = PUBLIC / "insights" / article["slug"] / "index.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    write(out, MARKER + "\n" + page)
    return out


def make_feature(soup, article):
    card = soup.new_tag("a", href=article["url"], attrs={"class": "feature"})
    tag = soup.new_tag("span", attrs={"class": "tag"})
    tag.string = article["category"]
    title = soup.new_tag("h2")
    title.string = article["title"]
    desc = soup.new_tag("p")
    desc.string = article["description"]
    read = soup.new_tag("span", attrs={"class": "read"})
    read.string = "Читать статью ↗"
    for node in (tag, title, desc, read):
        card.append(node)
    return card


def make_card(soup, article):
    search_text = " ".join([article["title"], article["description"], str(article["category"])]).lower()
    card = soup.new_tag(
        "a",
        href=article["url"],
        attrs={
            "class": "article-card",
            "data-cat": str(article["category"]),
            "data-text": search_text,
        },
    )
    tag = soup.new_tag("div", attrs={"class": "tag"})
    tag.string = str(article.get("category_ru", article["category"])).upper()
    title = soup.new_tag("h3")
    title.string = article["title"]
    desc = soup.new_tag("p")
    desc.string = article["description"]
    meta = soup.new_tag("div", attrs={"class": "meta"})
    meta.string = f"{article['minutes']} мин чтения · {article['date']} ↗"
    for node in (tag, title, desc, meta):
        card.append(node)
    return card


def build_catalog(articles):
    path = PUBLIC / "insights" / "index.html"
    soup = BeautifulSoup(path.read_text(encoding="utf-8"), "html.parser")

    first_feature = soup.find("a", class_="feature")
    if first_feature is None:
        fail("каталог: не найден блок .feature")
    featured_box = first_feature.parent
    featured_box.clear()
    featured = sorted(articles, key=lambda a: (not a["featured"], -date.fromisoformat(a["date"]).toordinal()))[:3]
    for article in featured:
        featured_box.append(make_feature(soup, article))

    cards = soup.select_one("#cards")
    if cards is None:
        fail("каталог: не найден #cards")
    cards.clear()
    for article in articles:
        cards.append(make_card(soup, article))

    toolbar = soup.select_one(".toolbar")
    if toolbar is None:
        fail("каталог: не найден .toolbar")
    for button in toolbar.select("button.filter"):
        button.decompose()
    for label, value, active in [("Все", "all", True)] + [
        (category, category, False) for category in sorted({str(a["category"]) for a in articles})
    ]:
        button = soup.new_tag(
            "button",
            attrs={"data-filter": value, "aria-pressed": "true" if active else "false"},
        )
        button["class"] = "filter active" if active else "filter"
        button.string = label
        toolbar.append(button)

    write(path, str(soup))


def update_home(articles):
    """Меняет только содержимое .nia-insights-list, не трогая остальную страницу."""
    path = PUBLIC / "index.html"
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(r'(<div class="nia-insights-list">)(.*?)(</div>)', re.S)
    if not pattern.search(text):
        fail("главная: не найден блок .nia-insights-list")

    items = "".join(
        f'<a href="{esc(article["url"])}"><span>{esc(str(article["category"]).upper())}</span>'
        f'<strong>{esc(article["title"])}</strong><small>Читать ↗</small></a>'
        for article in articles[:3]
    )
    write(path, pattern.sub(lambda m: m.group(1) + items + m.group(3), text, count=1))


def write_articles_json(articles):
    fields = ("title", "slug", "description", "category", "date", "author", "minutes", "url")
    data = [{key: article[key] for key in fields} for article in articles]
    path = PUBLIC / "insights" / "articles.json"
    write(path, json.dumps(data, ensure_ascii=False, indent=2) + "\n")


def write_sitemap(articles):
    pages = [
        ("/", STATIC_LAST_MOD, "1.0"),
        ("/audit/", STATIC_LAST_MOD, "0.9"),
        ("/brand/", STATIC_LAST_MOD, "0.8"),
        ("/insights/", max([STATIC_LAST_MOD] + [a["date"] for a in articles]), "0.8"),
    ] + [(a["url"], a["date"], "0.7") for a in articles]

    rows = "\n".join(
        f"  <url>\n    <loc>{SITE}{url}</loc>\n    <lastmod>{lastmod}</lastmod>\n    <priority>{priority}</priority>\n  </url>"
        for url, lastmod, priority in pages
    )
    xml = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{rows}\n</urlset>\n"
    )
    write(PUBLIC / "sitemap.xml", xml)


def remove_stale_pages(articles):
    """Удаляет страницы, сгенерированные прошлыми сборками, если статья исчезла."""
    expected = {a["slug"] for a in articles}
    root = PUBLIC / "insights"
    removed = []
    for directory in sorted(root.iterdir()):
        if not directory.is_dir() or directory.name in expected:
            continue
        page = directory / "index.html"
        if page.is_file() and page.read_text(encoding="utf-8").startswith(MARKER):
            shutil.rmtree(directory)
            removed.append(directory.name)
    return removed


def main():
    articles = load_articles()
    for article in articles:
        related = [x for x in articles if x["slug"] != article["slug"] and x["category"] == article["category"]]
        related += [x for x in articles if x["slug"] != article["slug"] and x not in related]
        render_article(article, related)

    removed = remove_stale_pages(articles)
    build_catalog(articles)
    update_home(articles)
    write_articles_json(articles)
    write_sitemap(articles)

    drafts = [a for a in CONTENT.glob("*.md")]
    print(f"опубликовано статей: {len(articles)}")
    if removed:
        print(f"удалены страницы: {', '.join(removed)}")
    print("обновлены: insights/*/index.html, insights/index.html, insights/articles.json, index.html, sitemap.xml")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # noqa: BLE001 — хотим понятное сообщение вместо трейса
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(1)
